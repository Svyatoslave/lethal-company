import assert from 'node:assert/strict';
import { test } from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { Actor } from '../server/game.js';

test('cooperative terminals keep clues separate and award credits once', async () => {
  const root = path.resolve(os.tmpdir());
  const dir = fs.mkdtempSync(path.join(root, 'raid-tasks-'));
  process.env.DATA_DIR = dir;
  const { db, q } = await import('../server/db.js');
  const g = await import('../server/game.js');
  const { playerSnapshot, staffSnapshot } = await import('../server/snapshot.js');
  const admin: Actor = { role: 'admin', playerId: null, label: 'ADMIN' };
  const operator: Actor = { role: 'operator', playerId: null, label: 'OPERATOR' };
  const crew: Actor = { role: 'player', playerId: 1, label: 'CREW' };
  const other: Actor = { role: 'player', playerId: 2, label: 'OTHER' };
  const monster: Actor = { role: 'player', playerId: 3, label: 'MONSTER' };
  const opts = { name: 'B-12', employeeText: 'INDICATOR: YELLOW', operatorText: 'YELLOW = OPEN 7316', answer: 'Open 7316', reward: 100 };
  const rejects = (fn: () => unknown, status: number) => assert.throws(fn, (e: unknown) => e instanceof g.GameError && e.status === status);
  try {
    g.createMission({ startBalance: 0 }, admin);
    for (const [id, role] of [[1, 'crew'], [2, 'crew'], [3, 'monster']] as const) {
      q.run('INSERT INTO players (id,callsign,role,join_code,created_at) VALUES (?,?,?,?,?)', id, `P${id}`, role, `CODE${id}`, Date.now());
    }
    rejects(() => g.saveTask(null, opts, operator), 403);
    rejects(() => g.saveTask(null, { ...opts, reward: -1 }, admin), 400);
    g.saveTask(null, opts, admin);
    const task = staffSnapshot('admin').tasks[0];
    assert.equal(task.answer, 'OPEN 7316');
    assert.ok(task.token);
    assert.equal(playerSnapshot(1).tasks.length, 0);
    assert.equal(staffSnapshot('operator').tasks[0].operatorText, undefined);
    assert.equal(staffSnapshot('operator').tasks[0].employeeText, '');
    rejects(() => g.activateTask(task.token, crew), 409);
    g.startMission(admin);
    rejects(() => g.activateTask(task.token, monster), 403);
    rejects(() => g.activateTask('not-a-valid-token', crew), 404);
    g.activateTask(task.token, crew);
    g.activateTask(task.token, crew);
    assert.equal(staffSnapshot('admin').events.filter(e => e.text.startsWith('Terminal activated')).length, 1);
    rejects(() => g.activateTask(task.token, other), 409);
    rejects(() => g.solveTask(task.id, opts.answer, other), 403);
    rejects(() => g.solveTask(task.id, opts.answer, operator), 403);
    rejects(() => g.saveTask(task.id, opts, admin), 409);
    rejects(() => g.deleteTask(task.id, admin), 409);
    const employeeView = JSON.stringify(playerSnapshot(1).tasks);
    assert.equal(employeeView.includes(opts.operatorText), false);
    assert.equal(employeeView.includes('answer'), false);
    assert.equal(employeeView.includes(task.token!), false);
    const operatorView = staffSnapshot('operator').tasks[0];
    assert.equal(operatorView.operatorText, opts.operatorText);
    assert.equal(operatorView.employeeText, '');
    assert.equal(operatorView.answer, undefined);
    assert.equal(operatorView.token, undefined);
    assert.equal(playerSnapshot(2).tasks.length, 0);
    assert.equal(playerSnapshot(3).tasks.length, 0);
    g.pauseMission('test', admin);
    rejects(() => g.solveTask(task.id, opts.answer, crew), 423);
    rejects(() => g.activateTask(task.token, crew), 423);
    g.resumeMission(admin);
    assert.deepEqual(g.solveTask(task.id, 'wrong', crew), { correct: false, already: false });
    assert.equal(g.balanceOf(g.currentMission()!.id), 0);
    rejects(() => g.solveTask(task.id, opts.answer, crew), 429);
    q.run('UPDATE tasks SET last_attempt_at = ? WHERE id = ?', Date.now() - 4000, task.id);
    assert.deepEqual(g.solveTask(task.id, '  open   7316 ', crew), { correct: true, already: false });
    assert.equal(g.balanceOf(g.currentMission()!.id), 100);
    assert.equal(g.quotaProgressOf(g.currentMission()!.id), 0);
    assert.equal(g.solveTask(task.id, opts.answer, crew).already, true);
    assert.equal(g.balanceOf(g.currentMission()!.id), 100);
    assert.equal(q.all('SELECT * FROM transactions WHERE kind = ?', 'task').length, 1);
    rejects(() => g.releaseTask(task.id, admin), 409);
    rejects(() => g.activateTask(task.token, crew), 409);
    g.saveTask(null, { ...opts, name: 'SECOND' }, admin);
    const second = staffSnapshot('admin').tasks[1];
    g.activateTask(second.token, crew);
    g.releaseTask(second.id, admin);
    assert.equal(playerSnapshot(1).tasks.some(t => t.id === second.id), false);
    g.activateTask(second.token, other);
    g.releaseTask(second.id, admin);
    g.saveTask(second.id, { ...opts, name: 'EDITED' }, admin);
    assert.equal(staffSnapshot('admin').tasks[1].token, second.token);
    g.deleteTask(second.id, admin);
    assert.equal(staffSnapshot('admin').tasks.length, 1);
    g.createMission({}, admin);
    g.startMission(admin);
    assert.equal(staffSnapshot('admin').tasks.length, 0);
    rejects(() => g.activateTask(task.token, crew), 404);
    rejects(() => g.solveTask(task.id, opts.answer, crew), 404);
  } finally {
    db.close();
    const relative = path.relative(root, dir);
    if (relative && !relative.startsWith('..') && !path.isAbsolute(relative)) fs.rmSync(dir, { recursive: true, force: true });
  }
});
